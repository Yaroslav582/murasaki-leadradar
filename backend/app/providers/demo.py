def _slugify(value: str) -> str:
    translit = {
        "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
        "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
        "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
        "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch", "ъ": "",
        "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya", " ": "", "-": "",
    }
    result = "".join(translit.get(char, char) for char in value.lower())
    result = re.sub(r"[^a-z0-9]", "", result)
    return result or "business"


def get_city_coords(city: str | None) -> tuple[float, float, list[str]] | None:
    """Case-insensitive city lookup with correct GPS coordinates and street names."""
    if not city:
        return None
    clean = city.strip()
    if clean in CITIES:
        return CITIES[clean]
    clean_lower = clean.lower()
    for name, data in CITIES.items():
        if name.lower() == clean_lower:
            return data
    return None


class DemoProvider(BaseProvider):
    """Deterministic demo data source so the product can be explored without API keys."""

    source = "demo"

    async def search(
        self,
        *,
        city: str,
        categories: list[str],
        query: str | None,
        limit: int,
        latitude: float | None = None,
        longitude: float | None = None,
        radius: int | None = None,
    ) -> list[PlaceResult]:
        categories = categories or CATEGORIES[:3]
        city = (city or "Москва").strip()
        matched = get_city_coords(city)
        base_lat, base_lng, streets = matched if matched else (55.7558, 37.6173, ["ул. Центральная"])
        if latitude is not None and longitude is not None:
            base_lat, base_lng = latitude, longitude
        rng = random.Random(f"{city}:{query}:{','.join(categories)}")
        results: list[PlaceResult] = []

        while len(results) < limit:
            category = categories[len(results) % len(categories)]
            prefix, names = NAME_PARTS.get(category, NAME_PARTS["Услуги"])
            idx = len(results)
            name = f"{rng.choice(prefix)} {rng.choice(names)}"
            if idx % 7 == 0:
                name = f"{name} #{idx // 7 + 1}"
            street = rng.choice(streets)
            address = f"{city}, {street}, {rng.randint(1, 120)}"
            phone = f"+7 ({rng.choice([495, 812, 843, 343, 383, 862, 861])}) " \
                    f"{rng.randint(200, 999):03d}-{rng.randint(10, 99):02d}-{rng.randint(10, 99):02d}"
            has_website = rng.random() < 0.3
            slug = _slugify(name)
            website = f"https://{slug}.ru" if has_website else None
            if idx % 11 == 0 and has_website:
                website = "https://example.com"

            socials: dict[str, str] = {}
            handle = rng.choice(HANDLES)
            if rng.random() < 0.5:
                socials["telegram"] = f"https://t.me/{handle}"
            if rng.random() < 0.35:
                socials["instagram"] = f"https://instagram.com/{handle}"
            if rng.random() < 0.35:
                digits = re.sub(r"\D", "", phone)[1:]
                socials["whatsapp"] = f"https://wa.me/7{digits}"

            hours = [
                "Пн–Пт 09:00–21:00",
                "Сб–Вс 10:00–20:00",
            ]
            if category == "Рестораны":
                hours = ["Ежедневно 12:00–00:00"]
            elif category == "Отели":
                hours = ["Круглосуточно"]

            results.append(
                PlaceResult(
                    name=name,
                    category=category,
                    city=city,
                    address=address,
                    phone=None if rng.random() < 0.08 else phone,
                    website_url=website,
                    rating=round(rng.uniform(3.8, 5.0), 1),
                    reviews_count=rng.randint(3, 850),
                    latitude=round(base_lat + rng.uniform(-0.09, 0.09), 6),
                    longitude=round(base_lng + rng.uniform(-0.12, 0.12), 6),
                    social_links=socials,
                    emails=[f"hello@{slug}.ru"] if has_website and rng.random() < 0.6 else [],
                    opening_hours=hours,
                    price_level=rng.choice([1, 2, 2, 3]),
                    source=self.source,
                    source_id=f"demo-{_slugify(city)}-{idx}-{slug}",
                )
            )
        return results
